namespace Kable.Generators.ProtocolPack;

using System;
using System.Collections.Generic;
using System.Globalization;
using System.Text;
using Kable.ProtocolPack.Models;

internal static class MapConstantsEmitter
{
    public static string Emit(string ns, string packTypeName, IList<MapSpec> maps)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated by Kable.Generators />");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace " + ns);
        sb.AppendLine("{");
        sb.AppendLine("    public static class " + packTypeName + "Maps");
        sb.AppendLine("    {");

        var used = new HashSet<string>(StringComparer.Ordinal);
        for (var i = 0; i < maps.Count; i++)
        {
            var map = maps[i];
            var ident = Unique(ProtocolPackIdentifiers.ToPascalIdentifier(map.Name), used, i);
            var addr = map.Addr ?? (map.Range != null ? map.Range.Start : 0);
            var length = ResolveLength(map);

            sb.AppendLine("        public const string " + ident + "Name = " + ProtocolPackCSharp.Literal(map.Name) + ";");
            sb.AppendLine("        public const int " + ident + "Addr = " + addr.ToString(CultureInfo.InvariantCulture) + ";");
            sb.AppendLine("        public const int " + ident + "Length = " + length.ToString(CultureInfo.InvariantCulture) + ";");
            if (!string.IsNullOrEmpty(map.Table))
            {
                sb.AppendLine("        public const string " + ident + "Table = " + ProtocolPackCSharp.Literal(map.Table) + ";");
            }

            if (!string.IsNullOrEmpty(map.Code))
            {
                sb.AppendLine("        public const string " + ident + "Code = " + ProtocolPackCSharp.Literal(map.Code) + ";");
            }

            sb.AppendLine();
        }

        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static int ResolveLength(MapSpec map)
    {
        if (map.Points.HasValue)
        {
            return map.Points.Value;
        }

        if (map.Range != null)
        {
            return map.Range.Count;
        }

        if (map.Values != null)
        {
            return map.Values.Count;
        }

        return 0;
    }

    private static string Unique(string ident, HashSet<string> used, int index)
    {
        if (used.Add(ident))
        {
            return ident;
        }

        var candidate = ident + (index + 1).ToString();
        used.Add(candidate);
        return candidate;
    }
}
