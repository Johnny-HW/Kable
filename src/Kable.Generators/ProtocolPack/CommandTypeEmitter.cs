namespace Kable.Generators.ProtocolPack;

using System;
using System.Collections.Generic;
using System.Text;
using Kable.ProtocolPack.Models;

internal static class CommandTypeEmitter
{
    public static string Emit(string ns, string typeKind, CommandSpec command)
    {
        var typeName = command.Name + "Command";
        var parameters = FormatParameters(command.Params);
        var template = command.Match ?? string.Empty;
        var attribute = FormatAttribute(template, command.Urgent);
        var formatExpression = template.IndexOf('{') >= 0
            ? ProtocolPackCSharp.Interpolated(template)
            : ProtocolPackCSharp.Literal(template);

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated by Kable.Generators />");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace " + ns);
        sb.AppendLine("{");
        sb.AppendLine("    " + attribute);
        sb.AppendLine("    public " + typeKind + " " + typeName + parameters + " : global::Kable.Generators.IDeviceWireCommand");
        sb.AppendLine("    {");
        sb.AppendLine("        public bool IsUrgent => " + (command.Urgent ? "true" : "false") + ";");
        sb.AppendLine();
        sb.AppendLine("        public string FormatWireMessage()");
        sb.AppendLine("        {");
        sb.AppendLine("            return " + formatExpression + ";");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static string FormatAttribute(string template, bool urgent)
    {
        var argument = ProtocolPackCSharp.Literal(template);
        if (urgent)
        {
            return "[global::Kable.Generators.DeviceCommand(" + argument + ", IsUrgent = true)]";
        }

        return "[global::Kable.Generators.DeviceCommand(" + argument + ")]";
    }

    private static string FormatParameters(IList<ParamSpec>? parameters)
    {
        if (parameters == null || parameters.Count == 0)
        {
            return string.Empty;
        }

        var parts = new string[parameters.Count];
        for (var i = 0; i < parameters.Count; i++)
        {
            var name = string.IsNullOrWhiteSpace(parameters[i].Name) ? "Arg" + i : parameters[i].Name;
            parts[i] = MapType(parameters[i].Type) + " " + name;
        }

        return "(" + string.Join(", ", parts) + ")";
    }

    private static string MapType(string? type)
    {
        if (string.Equals(type, "int", StringComparison.OrdinalIgnoreCase))
        {
            return "int";
        }

        if (string.Equals(type, "double", StringComparison.OrdinalIgnoreCase))
        {
            return "double";
        }

        return "string";
    }
}
