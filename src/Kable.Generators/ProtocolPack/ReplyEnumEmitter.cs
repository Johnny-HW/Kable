namespace Kable.Generators.ProtocolPack;

using System;
using System.Collections.Generic;
using System.Text;
using Kable.ProtocolPack.Models;

internal static class ReplyEnumEmitter
{
    public static string Emit(string ns, CommandSpec command)
    {
        var typeName = command.Name + "Reply";
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated by Kable.Generators />");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace " + ns);
        sb.AppendLine("{");
        sb.AppendLine("    public enum " + typeName);
        sb.AppendLine("    {");
        sb.AppendLine("        Ok,");

        var used = new HashSet<string>(StringComparer.Ordinal) { "Ok", "Unmatched" };
        var errors = command.Errors ?? Array.Empty<ErrorOutcomeSpec>();
        for (var i = 0; i < errors.Count; i++)
        {
            var ident = Unique(ProtocolPackIdentifiers.ToPascalIdentifier(errors[i].Name), used, i);
            sb.AppendLine("        " + ident + ",");
        }

        sb.AppendLine("        Unmatched");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static string Unique(string ident, HashSet<string> used, int index)
    {
        if (used.Add(ident))
        {
            return ident;
        }

        var candidate = ident + (index + 1).ToString();
        used.Add(candidate);
        return candidate;
    }
}
