namespace Kable.Generators.ProtocolPack;

using System.Globalization;
using System.Text;
using Kable.ProtocolPack.Models;

internal static class OptionsFactoryEmitter
{
    public static string Emit(string ns, string packTypeName, ProtocolPackDocument document)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated by Kable.Generators />");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace " + ns);
        sb.AppendLine("{");
        sb.AppendLine("    public static class " + packTypeName + "Protocol");
        sb.AppendLine("    {");
        sb.AppendLine("        public const string Codec = " + ProtocolPackCSharp.Literal(document.Codec) + ";");
        sb.AppendLine();
        sb.AppendLine("        public static global::Kable.Configuration.KableDeviceOptions CreateDeviceOptions()");
        sb.AppendLine("        {");
        sb.AppendLine("            return new global::Kable.Configuration.KableDeviceOptions");
        sb.AppendLine("            {");
        AppendInitializer(sb, document);
        sb.AppendLine("            };");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static void AppendInitializer(StringBuilder sb, ProtocolPackDocument document)
    {
        sb.AppendLine("                DeviceId = " + ProtocolPackCSharp.Literal(document.Name) + ",");
        var endpoint = document.Endpoint;
        if (endpoint == null)
        {
            return;
        }

        AppendString(sb, "Transport", endpoint.Transport);
        AppendString(sb, "Host", endpoint.Host);
        AppendInt(sb, "Port", endpoint.Port);
        AppendString(sb, "PortName", endpoint.PortName);
        AppendInt(sb, "BaudRate", endpoint.BaudRate);
        AppendString(sb, "Parity", endpoint.Parity);
        AppendInt(sb, "DataBits", endpoint.DataBits);
        AppendString(sb, "StopBits", endpoint.StopBits);
        AppendString(sb, "PipeName", endpoint.PipeName);
        AppendString(sb, "ServerName", endpoint.ServerName);
    }

    private static void AppendString(StringBuilder sb, string property, string? value)
    {
        if (string.IsNullOrEmpty(value))
        {
            return;
        }

        sb.AppendLine("                " + property + " = " + ProtocolPackCSharp.Literal(value) + ",");
    }

    private static void AppendInt(StringBuilder sb, string property, int? value)
    {
        if (!value.HasValue)
        {
            return;
        }

        sb.AppendLine("                " + property + " = " + value.Value.ToString(CultureInfo.InvariantCulture) + ",");
    }
}
